"""Each scenario starts with the line the lifecycle hook would print at session start.

The scenario suite sends prompts to `claude -p` with no hooks, so a scenario
carries the hook's line itself. The line is generated by running the real hook
in a deployment-shaped layout, so a wording change in the hook fails here
until the scenarios are regenerated, and can't drift silently.
"""

import json
import os
import subprocess
import sys

import pytest

from tests.checker_helpers import REPO_ROOT

SCENARIOS = json.loads((REPO_ROOT / "eval" / "scenarios.json").read_text())
FRAME = "[At session start, a hook injected this context:]\n"
# Where each default comes from: the personal machine's profile, and the work
# machine's profile that #17 adds.
SOURCES = {
    "github-issue-lifecycle": "hosts/personal.json",
    "jira-ticket-lifecycle": "hosts/work.json",
}


def hook_line(tmp_path, default):
    """The context line the deployed hook prints when `default` comes from its host profile."""
    host = SOURCES[default]
    data = tmp_path / default / "data"
    release = data / "releases" / "r"
    (release / "config" / "hooks").mkdir(parents=True)
    hook = REPO_ROOT / "config" / "hooks" / "lifecycle_default.py"
    (release / "config" / "hooks" / hook.name).write_bytes(hook.read_bytes())
    (release / "hosts").mkdir()
    (release / host).write_text(json.dumps({"defaultLifecycle": default}))
    (data / "current").symlink_to("releases/r")
    (data / "state.json").write_text(json.dumps({"host": host}))
    xdg = tmp_path / default / "xdg"
    xdg.mkdir()
    done = subprocess.run(
        [sys.executable, "-I", str(data / "current" / "config" / "hooks" / hook.name)],
        input=json.dumps({"hook_event_name": "SessionStart"}),
        capture_output=True,
        text=True,
        env={"PATH": os.environ.get("PATH", ""), "XDG_CONFIG_HOME": str(xdg)},
        check=True,
    )
    return json.loads(done.stdout)["hookSpecificOutput"]["additionalContext"]


@pytest.fixture(scope="module")
def lines(tmp_path_factory):
    root = tmp_path_factory.mktemp("lines")
    return {default: hook_line(root, default) for default in SOURCES}


def test_every_scenario_names_a_known_default():
    assert {s["id"]: s.get("sessionDefault") in SOURCES for s in SCENARIOS} == {
        s["id"]: True for s in SCENARIOS
    }


def test_every_prompt_starts_with_the_hooks_exact_line_for_its_default(lines):
    for s in SCENARIOS:
        prefix = FRAME + lines[s["sessionDefault"]] + "\n\n"
        # On a wording change in the hook, paste this prefix over the old one.
        assert s["prompt"].startswith(prefix), f"{s['id']} should start with {prefix!r}"
        assert len(s["prompt"]) > len(prefix), s["id"]


def test_the_imported_scenarios_keep_the_personal_machines_default():
    imported = {f"S-{n:02d}" for n in range(1, 28)}
    for s in SCENARIOS:
        if s["id"] in imported:
            assert s["sessionDefault"] == "github-issue-lifecycle", s["id"]


def test_new_rule_scenarios_cover_both_trackers():
    new = [s for s in SCENARIOS if "#15" in s.get("note", "")]
    assert len(new) >= 5
    assert all("new-rule-only" in s["tags"] for s in new)
    assert {s["sessionDefault"] for s in new} == set(SOURCES)
